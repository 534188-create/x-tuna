def frontend_sync_state(expected_sha256: str, current_sha256: str) -> str:
    if not re.fullmatch(r"[0-9a-f]{64}", str(expected_sha256 or ""), re.IGNORECASE):
        return "blocked"
    if not re.fullmatch(r"[0-9a-f]{64}", str(current_sha256 or ""), re.IGNORECASE):
        return "blocked"
    return "ready" if expected_sha256.lower() == current_sha256.lower() else "needs_sync"


def render_naive_sync_script() -> str:
    return """#!/usr/bin/env python3
import os, re, stat, subprocess, sys

COMMAND = "/usr/local/sbin/lucx-post-configure"


def failure():
    sys.stderr.write("[lucx-naive-sync] Синхронизация не выполнена.\\n")
    return 1


def main(args):
    if len(args) != 1 or not re.fullmatch(r"[1-9][0-9]{0,9}", args[0]):
        return failure()
    if int(args[0]) > 2147483647:
        return failure()
    try:
        metadata = os.lstat(COMMAND)
        if (not stat.S_ISREG(metadata.st_mode) or metadata.st_uid != 0
                or metadata.st_mode & 0o022 or not metadata.st_mode & stat.S_IXUSR):
            return failure()
        # Общая транзакция Engine владеет lock, валидацией и receipt/rollback.
        # Не прерываем её таймером посредника во время commit.
        result = subprocess.run(
            [COMMAND, "--sync-naive-inbound", args[0]],
            stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            env={"PATH": "/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin",
                 "LANG": "C.UTF-8", "LC_ALL": "C.UTF-8"}, check=False,
        )
        return 0 if result.returncode == 0 else failure()
    except OSError:
        return failure()


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
"""


